import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
const root = resolve(import.meta.dirname, "../..");
const require = createRequire(resolve(root, "apps/mobile/package.json"));
const dist = dirname(require.resolve("katex/dist/katex.min.js"));
let css = readFileSync(resolve(dist, "katex.min.css"), "utf8");
css = css.replace(/src:[^;]+;/g, src => {
 const file = /url\(fonts\/([^)]*\.woff2)\)/.exec(src)?.[1];
 return file ? `src:url(data:font/woff2;base64,${readFileSync(resolve(dist, "fonts", file)).toString("base64")}) format('woff2');` : src;
});
const js = readFileSync(resolve(dist, "katex.min.js"), "utf8").replace(/<\/script/gi, "<\\/script");
const target = resolve(root, "apps/mobile/src/ui/rich-content/math-assets.ts");
writeFileSync(target, "// Generated by scripts/mobile/bundle_math.mjs. KaTeX MIT; see assets/licenses/KaTeX.txt.\nexport const MATH_JS = " + JSON.stringify(js) + ";\nexport const MATH_CSS = " + JSON.stringify(css) + ";\n");
mkdirSync(resolve(root, "apps/mobile/assets/licenses"), { recursive: true });
writeFileSync(resolve(root, "apps/mobile/assets/licenses/KaTeX.txt"), readFileSync(resolve(dist, "../LICENSE"), "utf8"));
process.stdout.write("Bundled offline KaTeX and WOFF2 fonts.\n");
